// Function to check if it is safe to place num at mat[row][col]
bool isSafe(vector<vector<int>> &mat, int row, int col, int num, int size) {

    // Check if num exist in the row
    for (int x = 0; x <= (size - 1); x++)
        if (mat[row][x] == num)
            return false;

    // Check if num exist in the col
    for (int x = 0; x <= (size - 1); x++)
        if (mat[x][col] == num)
            return false;

    // Check if num exist in the 3x3 sub-matrix
    int startRow = row - (row % int(sqrt(size))), startCol = col - (col % int(sqrt(size)));

    for (int i = 0; i < int(sqrt(size)); i++)
        for (int j = 0; j < int(sqrt(size)); j++)
            if (mat[i + startRow][j + startCol] == num)
                return false;

    return true;
}

// Function to solve the Sudoku problem
bool solveSudokuRec(vector<vector<int>> &mat, int row, int col, int size, time_t timer1) {
    time_t timer2;
    time(&timer2);

    if (difftime(timer2, timer1) >= 120) {
        return false;
    }
     
    
    int n = mat.size();

    // base case: Reached nth column of last row
    if (row == n - 1 && col == n)
        return true;

    // If last column of the row go to next row
    if (col == n) {
        row++;
        col = 0;
    }

    // If cell is already occupied then move forward
    if (mat[row][col] != 0)
        return solveSudokuRec(mat, row, col + 1, size, timer1);

    for (int num = 1; num <= n; num++) {

        // If it is safe to place num at current position
        if (isSafe(mat, row, col, num, size)) {
            mat[row][col] = num;
            if (solveSudokuRec(mat, row, col + 1, size, timer1))
                return true;
            mat[row][col] = 0;
        }
    }
  
  	return false;
}

void solveSudoku(vector<vector<int>> &mat, int size, time_t timer1) {
  	solveSudokuRec(mat, 0, 0, size, timer1);
}

